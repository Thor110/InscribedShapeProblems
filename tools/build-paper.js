#!/usr/bin/env node
// Builds the preprint from PAPER.md, with PROOFS.md appended as the appendix:
//   pages/paper.html   static page (maths pre-rendered to SVG, no CDN needed)
//   PAPER.pdf          the same, printed by the pre-installed Chromium
//
//   node tools/build-paper.js          # both
//   node tools/build-paper.js --html   # page only
'use strict';
const fs = require('fs'), path = require('path');
const { marked } = require('marked');
const { mathjax } = require('mathjax-full/js/mathjax.js');
const { TeX } = require('mathjax-full/js/input/tex.js');
const { SVG } = require('mathjax-full/js/output/svg.js');
const { liteAdaptor } = require('mathjax-full/js/adaptors/liteAdaptor.js');
const { RegisterHTMLHandler } = require('mathjax-full/js/handlers/html.js');
const { AllPackages } = require('mathjax-full/js/input/tex/AllPackages.js');

const ROOT = path.join(__dirname, '..'), REPO = 'https://github.com/Thor110/InscribedSquareProblem/blob/main/';
const adaptor = liteAdaptor(); RegisterHTMLHandler(adaptor);
const doc = mathjax.document('', { InputJax: new TeX({ packages: AllPackages }), OutputJax: new SVG({ fontCache: 'local' }) });
const tex2svg = (tex, display) => adaptor.outerHTML(doc.convert(tex.replace(/\\\*/g, '*'), { display }));

// GitHub-style heading slugs, so links such as PROOFS.md#theorem-6--a-computer-assisted-certificate work.
const slug = s => s.toLowerCase().replace(/<[^>]+>/g, '').replace(/[^\p{L}\p{N}\s-]/gu, '').trim().replace(/\s/g, '-');

function render(md) {
  // Take the maths out before markdown sees it (underscores and asterisks would be mangled).
  const math = [];
  const keep = (tex, display) => { math.push(tex2svg(tex, display)); return `@@MATH${math.length - 1}@@`; };
  md = md.replace(/\$\$([\s\S]+?)\$\$/g, (_, t) => keep(t, true)).replace(/(?<![\\$])\$([^$\n]+?)\$/g, (_, t) => keep(t, false));
  const used = new Map();
  const renderer = new marked.Renderer();
  renderer.heading = function ({ tokens, depth }) {
    const text = this.parser.parseInline(tokens);
    let id = slug(text.replace(/@@MATH\d+@@/g, '')); const n = used.get(id) || 0; used.set(id, n + 1); if (n) id += '-' + n;
    return `<h${depth} id="${id}">${text}</h${depth}>\n`;
  };
  renderer.link = function ({ href, tokens }) {
    const text = this.parser.parseInline(tokens);
    if (/^pages\//.test(href)) href = href.slice(6);                          // page → page
    else if (/^(PROOFS|README)\.md#/.test(href)) href = '#' + href.split('#')[1];   // into the appendix
    else if (!/^(https?:|#|mailto:)/.test(href)) href = REPO + href;           // other repository files
    return `<a href="${href}">${text}</a>`;
  };
  let html = marked.parse(md, { renderer, gfm: true });
  return html.replace(/@@MATH(\d+)@@/g, (_, i) => math[+i]).replace(/<p>(<mjx-container[^>]*display="true"[\s\S]*?<\/mjx-container>)<\/p>/g, '$1');
}

const paper = fs.readFileSync(path.join(ROOT, 'PAPER.md'), 'utf8');
// Appendix: PROOFS.md from its notation section on, headings one level down.
const proofs = fs.readFileSync(path.join(ROOT, 'PROOFS.md'), 'utf8').split('## Notation')[1];
const appendix = '\n\n## Appendix: complete proofs\n\nThis appendix is the repository file `PROOFS.md`, reproduced verbatim from its notation section on.\n\n### Notation' + proofs.replace(/^## /gm, '### ');
const body = render(paper + appendix);

const page = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>Inscribed Polytopes Preprint</title>
<!-- Generated by tools/build-paper.js from PAPER.md and PROOFS.md. Edit those, not this file. -->
<style>
  :root{--bg:#fbfaf7;--fg:#1d1c1a;--muted:#6b6862;--rule:#ddd8cf;--link:#2f6a55;--quote:#f1eee7;}
  @media (prefers-color-scheme: dark){:root{--bg:#0d0d12;--fg:#e2dfd9;--muted:#8d8a84;--rule:#2a2a33;--link:#6fbf9f;--quote:#15151c;}}
  *{box-sizing:border-box;}
  body{margin:0;background:var(--bg);color:var(--fg);font:17px/1.6 Georgia,'Times New Roman',serif;}
  main{max-width:780px;margin:0 auto;padding:32px 16px 64px;}
  h1{font-size:1.65em;line-height:1.25;margin:0 0 .4em;}
  h2{font-size:1.3em;margin:2em 0 .5em;border-bottom:1px solid var(--rule);padding-bottom:.2em;}
  h3{font-size:1.1em;margin:1.6em 0 .4em;}
  h4{font-size:1em;}
  a{color:var(--link);}
  blockquote{margin:1em 0;padding:.6em 1em;background:var(--quote);border-left:3px solid var(--link);}
  blockquote p{margin:.3em 0;}
  table{border-collapse:collapse;margin:1em 0;font-size:.88em;display:block;overflow-x:auto;}
  th,td{border:1px solid var(--rule);padding:4px 8px;vertical-align:top;}
  code{font-size:.88em;background:var(--quote);padding:0 3px;border-radius:3px;}
  pre{background:var(--quote);padding:10px;overflow-x:auto;}
  hr{border:0;border-top:1px solid var(--rule);margin:2em 0;}
  mjx-container[display="true"]{display:block;text-align:center;margin:.8em 0;overflow-x:auto;overflow-y:hidden;}
  mjx-container svg{max-width:100%;}
  .nav{font:12px 'Courier New',monospace;letter-spacing:.08em;text-transform:uppercase;margin-bottom:24px;display:flex;gap:18px;flex-wrap:wrap;}
  .nav a{color:var(--muted);text-decoration:none;}
  @media print{.nav{display:none;} body{font-size:11pt;background:#fff;color:#000;} main{max-width:none;padding:0;} h2{break-after:avoid;} blockquote,table,mjx-container{break-inside:avoid;}}
</style>
</head>
<body>
<main>
<div class="nav"><a href="../index.html">← Back to suite</a><a href="${REPO}PAPER.md">Markdown source</a><a href="${REPO}PAPER.pdf">PDF</a></div>
${body}
</main>
</body>
</html>
`;
fs.writeFileSync(path.join(ROOT, 'pages', 'paper.html'), page);
console.log('wrote pages/paper.html (' + (page.length / 1024).toFixed(0) + ' KB)');

if (!process.argv.includes('--html')) (async () => {
  const { chromium } = require('playwright');
  const b = await chromium.launch(), p = await b.newPage();
  await p.goto('file://' + path.join(ROOT, 'pages', 'paper.html'));
  await p.emulateMedia({ media: 'print', colorScheme: 'light' });
  await p.pdf({ path: path.join(ROOT, 'PAPER.pdf'), format: 'A4', margin: { top: '20mm', bottom: '20mm', left: '18mm', right: '18mm' }, displayHeaderFooter: true, headerTemplate: '<span></span>', footerTemplate: '<div style="font-size:8px;width:100%;text-align:center;color:#888"><span class="pageNumber"></span> / <span class="totalPages"></span></div>' });
  await b.close();
  console.log('wrote PAPER.pdf (' + (fs.statSync(path.join(ROOT, 'PAPER.pdf')).size / 1024).toFixed(0) + ' KB)');
})();
